const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs/promises');
const { _electron } = require('playwright');
const root = path.resolve(__dirname, '../..');
const outputDir = path.join(root, 'output/playwright');

(async () => {
  await fs.mkdir(outputDir, { recursive: true });
  const env = { ...process.env };
  delete env.ELECTRON_RUN_AS_NODE;
  const app = await _electron.launch({ args: [path.join(root, 'desktop-app/main.cjs')], env });
  const errors = [];
  const checks = [];
  try {
    const page = await app.firstWindow();
    page.on('pageerror', (error) => errors.push(error.message));
    page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
    await page.waitForFunction(() => window.q1lensTimeline?.getSnapshot().ready && document.getElementById('run-status').textContent === 'READY', null, { timeout: 90000 });
    checks.push('real Python demo analysis and Pixi canvas loaded');
    const snapshot = () => page.evaluate(() => window.q1lensTimeline.getSnapshot());
    let state = await snapshot();
    assert.equal(state.sequencerCount, 8);
    assert.equal(state.viewMode, 'normal');
    assert.equal(state.playing, false);
    assert.equal(await page.evaluate(() => typeof window.require), 'undefined');
    await page.screenshot({ path: path.join(outputDir, 'desktop-start.png') });
    console.log('INITIAL', JSON.stringify({ viewport: page.viewportSize(), bounds: await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].getBounds()), events: state.eventCount }));
    await page.locator('#playback-toggle').click();
    await page.waitForFunction((before) => window.q1lensTimeline.getSnapshot().playheadNs > before + 5, state.playheadNs);
    await page.locator('#playback-toggle').click();
    state = await snapshot();
    assert.equal(state.playing, false);
    const paused = state.playheadNs;
    await page.waitForTimeout(200);
    assert.equal((await snapshot()).playheadNs, paused);
    checks.push('playback advances and pause holds time');
    await page.locator('#playback-speed').selectOption('2');
    assert.equal((await snapshot()).playbackSpeed, 2);
    await page.locator('#timeline-scrubber').focus();
    await page.keyboard.press('Home');
    await page.keyboard.press('ArrowRight');
    assert.equal((await snapshot()).playing, false);
    checks.push('speed selector and keyboard scrubber');
    const canvas = page.locator('#pixi-stage canvas');
    const box = await canvas.boundingBox();
    await page.mouse.move(box.x + box.width * .65, box.y + Math.min(130, box.height / 2));
    const beforeZoom = (await snapshot()).timeWindow;
    await page.mouse.wheel(0, -200);
    await page.waitForTimeout(150);
    const zoomed = (await snapshot()).timeWindow;
    assert.ok(zoomed.maxNs - zoomed.minNs < beforeZoom.maxNs - beforeZoom.minNs);
    await page.mouse.down();
    await page.mouse.move(box.x + box.width * .65 + 50, box.y + Math.min(130, box.height / 2), { steps: 8 });
    await page.mouse.up();
    await page.waitForTimeout(150);
    assert.notEqual((await snapshot()).timeWindow.minNs, zoomed.minNs);
    assert.equal((await snapshot()).selected, null);
    checks.push('pointer zoom and pan without accidental selection');
    await page.locator('#fit-all').click();
    state = await snapshot();
    assert.deepEqual(state.timeWindow, state.fullTimeExtent);
    await page.locator('#showcase-mode').click();
    assert.equal((await snapshot()).viewMode, 'showcase');
    await page.screenshot({ path: path.join(outputDir, 'desktop-flow.png') });
    await page.locator('#debug-mode').click();
    assert.equal((await snapshot()).viewMode, 'debug');
    await page.locator('#normal-mode').click();
    await page.locator('#pixi-stage').focus();
    await page.keyboard.press('Space');
    assert.equal((await snapshot()).playing, true);
    await page.keyboard.press('Space');
    await page.keyboard.press('Home');
    assert.equal((await snapshot()).playheadNs, (await snapshot()).fullTimeExtent.minNs);
    checks.push('all three views; Space/Home/Fit controls');
    await page.mouse.click(box.x + 360, box.y + 92);
    await page.screenshot({ path: path.join(outputDir, 'desktop-selected.png') });
    console.log('SELECTION', (await snapshot()).selected?.type || 'none');
    assert.equal((await snapshot()).selected?.type, 'event');
    assert.ok(await page.evaluate(() => document.getElementById('inspector-details').getBoundingClientRect().bottom <= document.querySelector('.diagnostics-panel').getBoundingClientRect().top));
    checks.push('selected event inspector does not overlap analysis notes');
    const original = await page.evaluate(() => window.q1lensDesktop.getState());
    const invalidFile = path.join(outputDir, 'invalid-timeline.json');
    await fs.writeFile(invalidFile, '{"hello":true}');
    await app.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }); }, invalidFile);
    await page.locator('#open-project').click();
    await page.locator('#error-banner').waitFor({ state: 'visible' });
    await page.waitForFunction(() => !document.getElementById('open-project').disabled);
    await page.waitForFunction(() => document.querySelector('#pixi-stage canvas').getBoundingClientRect().height === document.getElementById('pixi-stage').clientHeight);
    assert.equal((await page.evaluate(() => window.q1lensDesktop.getState())).projectPath, original.projectPath);
    assert.equal((await snapshot()).eventCount, state.eventCount);
    checks.push('invalid file shows error and retains previous project and scene');
    await page.locator('#dismiss-error').click();
    await page.waitForFunction(() => document.querySelector('#pixi-stage canvas').getBoundingClientRect().height === document.getElementById('pixi-stage').clientHeight);
    await app.evaluate(({ dialog }) => { dialog.showOpenDialog = async () => ({ canceled: true, filePaths: [] }); });
    await page.locator('#open-project').click();
    await page.waitForFunction(() => !document.getElementById('open-project').disabled);
    assert.equal((await page.evaluate(() => window.q1lensDesktop.getState())).projectPath, original.projectPath);
    checks.push('canceling native picker preserves project');
    await page.locator('#select-python').click();
    await page.waitForFunction(() => !document.getElementById('open-project').disabled);
    assert.equal((await page.evaluate(() => window.q1lensDesktop.getState())).pythonPath, original.pythonPath);
    checks.push('canceling interpreter selection preserves Python');
    await app.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }); }, path.join(root, 'examples/basic-transmon/qbstimeline.yml'));
    await page.locator('#open-project').click();
    await page.waitForFunction(() => document.getElementById('project-name').textContent === 'basic-transmon' && !document.getElementById('open-project').disabled, null, { timeout: 90000 });
    assert.ok((await snapshot()).eventCount > 0);
    await page.locator('#reanalyze').click();
    await page.waitForFunction(() => !document.getElementById('open-project').disabled);
    assert.equal(await page.locator('#run-status').textContent(), 'READY');
    checks.push('QBS project selection, compilation and reanalysis');
    await page.locator('#open-demo').click();
    await page.waitForFunction(() => document.getElementById('project-name').textContent === 'three-peak-demo1' && !document.getElementById('open-project').disabled);
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1100, 760));
    await page.waitForTimeout(300);
    const fit = await page.evaluate(() => {
      const result = { width: innerWidth, height: innerHeight, scrollWidth: document.documentElement.scrollWidth, scrollHeight: document.documentElement.scrollHeight };
      result.regions = ['.app-header', '.timeline-panel', '.transport', '.status-bar', '.side-panel'].map(selector => {
        const r = document.querySelector(selector).getBoundingClientRect();
        return { selector, left: r.left, top: r.top, right: r.right, bottom: r.bottom };
      });
      return result;
    });
    assert.ok(fit.scrollWidth <= fit.width && fit.scrollHeight <= fit.height);
    assert.ok(fit.regions.every(r => r.left >= 0 && r.top >= 0 && r.right <= fit.width && r.bottom <= fit.height));
    await page.screenshot({ path: path.join(outputDir, 'desktop-compact.png') });
    checks.push('1100×760 window: primary controls and workspace stay in viewport');
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(960, 640));
    await page.waitForFunction(() => document.querySelector('#pixi-stage canvas').getBoundingClientRect().height === document.getElementById('pixi-stage').clientHeight);
    assert.ok(await page.evaluate(() => {
      const transport = document.querySelector('.transport').getBoundingClientRect();
      const open = document.getElementById('open-project').getBoundingClientRect();
      const reset = document.getElementById('reset-view').getBoundingClientRect();
      return document.documentElement.scrollWidth <= innerWidth && transport.bottom <= innerHeight && open.right <= innerWidth && reset.right <= transport.right;
    }));
    checks.push('minimum 960×640 window keeps transport and project controls accessible');
    console.log('FIT', JSON.stringify(fit));
    console.log('ERRORS', JSON.stringify(errors));
    assert.deepEqual(errors, []);
    console.log('PASS', JSON.stringify(checks));
  } catch (error) {
    const page = await app.firstWindow();
    console.log('ERRORS', JSON.stringify(errors));
    console.log('BODY', await page.locator('body').innerText());
    await page.screenshot({ path: path.join(outputDir, 'desktop-failure.png') });
    throw error;
  } finally {
    await app.close();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
