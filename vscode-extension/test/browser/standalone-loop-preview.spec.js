const path = require("node:path");
const { execFileSync } = require("node:child_process");
const { test, expect } = require("./helpers");

function fixtures() {
  const repo = path.resolve(__dirname, "../../..");
  return JSON.parse(execFileSync(process.env.Q1LENS_BROWSER_PYTHON || "python", ["-c", [
    "import json", "from contextlib import redirect_stdout", "from io import StringIO",
    "from pathlib import Path", "from tempfile import TemporaryDirectory",
    "from q1timeline.cli import main", "from q1timeline.render.html import render_html",
    "source = 'move 3,R0\\nnop\\nshot: acquire 0,0,40\\nwait 960\\nloop R0,@shot\\nstop'",
    "def analyze(file, *options):",
    "    output = StringIO()",
    "    with redirect_stdout(output):",
    "        assert main(['analyze', str(file), '--format', 'vscode-json', '--include-timeline-ir', '--no-render', *options]) == 0",
    "    return json.loads(output.getvalue())['timeline_ir']",
    "def view(ir):",
    "    loop = next(event for event in ir['events'] if event['kind'] == 'loop_block')",
    "    events = {event['id']: event for event in ir['events']}",
    "    first = [events[id] for id in loop['meta']['first_iteration_event_ids']]",
    "    return dict(html=render_html(ir), loop=loop, first=first)",
    "with TemporaryDirectory(prefix='q1lens-loop-preview-') as work:",
    "    file = Path(work) / 'loop.q1asm'",
    "    file.write_text(source, encoding='utf-8')",
    "    one = view(analyze(file))",
    "    key = one['loop']['meta']['loop_preview_key']",
    "    two = view(analyze(file, '--loop-preview', f'{key}=2'))",
    "print(json.dumps(dict(one=one, two=two)))",
  ].join("\n")], { cwd: repo, encoding: "utf8", timeout: 10000,
    env: { ...process.env, PYTHONPATH: path.join(repo, "src") } }));
}

async function open(page, dataset) {
  await page.goto("about:blank");
  await page.setContent(dataset.html);
  const svg = page.locator("#timeline-root > svg");
  const loop = svg.locator(`.loop-bracket-start[data-event-id="${dataset.loop.id}"]`);
  const inspector = page.locator("#event-inspector-fields");
  return {
    svg,
    loop,
    // The upper part of the bracket hitbox is outside the overlapping RT blocks.
    selectLoop: () => loop.locator(".loop-bracket-hitbox").click({position: {x: 24, y: 4}}),
    field: (label) => inspector.getByText(label, {exact: true}).locator("xpath=following-sibling::dd[1]"),
  };
}

test("standalone loop preview navigates to first visible evidence after mode and filter changes", async ({page}) => {
  const {one} = fixtures();
  const {svg, loop, selectLoop, field} = await open(page, one);
  const first = page.getByRole("button", {name: "Open first iteration", exact: true});
  const next = page.getByRole("button", {name: "Show next iteration", exact: true});
  const [issue, acquire] = one.first;
  expect([issue.kind, acquire.kind]).toEqual(["q1_issue", "acquire"]);

  for (const [mode, target] of [["Normal", acquire], ["Debug", issue], ["Normal", acquire]]) {
    await selectLoop();
    await page.getByRole("button", {name: mode, exact: true}).click();
    await expect(loop).toHaveClass(/is-selected/);
    await expect(field("Loop iterations")).toHaveText("1/3");
    await expect(next).toHaveCount(0);
    await first.click();
    await expect(svg.locator(".is-selected")).toHaveAttribute("data-event-id", target.id);
    await expect(field("Source")).toHaveText("loop.q1asm:3");
  }

  await selectLoop();
  const filter = page.getByRole("searchbox", {name: "Filter source or kind"});
  await filter.fill(`${issue.id} q1_issue`);
  await expect(first).toHaveCount(0);
  await page.getByRole("button", {name: "Debug", exact: true}).click();
  await expect(first).toBeVisible();
  await page.getByRole("button", {name: "Normal", exact: true}).click();
  await expect(first).toHaveCount(0);
  await filter.clear();
  await expect(first).toBeVisible();
});

test("standalone loop preview reports the iterations already generated by the CLI", async ({page}) => {
  const {one, two} = fixtures();
  expect(two.loop.meta.shown_iterations).toEqual([0, 1]);
  expect(two.loop.meta.count).toEqual(one.loop.meta.count);
  const previous = await open(page, one);
  await previous.selectLoop();
  const range = await previous.field("RT preview range").innerText();
  const title = await previous.loop.locator("title").textContent();
  const extent = await previous.svg.getAttribute("data-time-max");

  const {svg, loop, selectLoop, field} = await open(page, two);
  await selectLoop();
  await expect(field("Loop iterations")).toHaveText("2/3");
  await expect(field("RT preview range")).toHaveText(range);
  await expect(loop.locator("title")).toHaveText(title);
  await expect(svg).toHaveAttribute("data-time-max", extent);
  await expect(page.getByRole("button", {name: "Show next iteration", exact: true})).toHaveCount(0);
  await page.getByRole("button", {name: "Open first iteration", exact: true}).click();
  await expect(svg.locator(".is-selected")).toHaveAttribute("data-event-id", two.first[1].id);
});

test("standalone Normal activates the RT acquire and both loop brackets in existing tab order", async ({page}) => {
  const {one} = fixtures();
  const acquire = one.first.find((event) => event.kind === "acquire");
  for (const [selector, hitbox, position, tabs, id] of [
    [".loop-bracket-start", ".loop-bracket-hitbox", {x: 24, y: 4}, 1, one.loop.id],
    [".loop-bracket-end", ".loop-bracket-hitbox", {x: 24, y: 4}, 2, one.loop.id],
    [`.kind-acquire[data-event-id="${acquire.id}"]`, "rect", undefined, 5, acquire.id],
  ]) {
    const {svg, field} = await open(page, one);
    const target = svg.locator(selector);
    await expect(target).toHaveAttribute("role", "button");
    for (let step = 0; step < tabs; step++) await page.keyboard.press("Tab");
    await expect(target).toBeFocused();
    await page.evaluate(() => {
      window.activatedEvents = [];
      window.addEventListener("q1timeline:eventClick", (event) => window.activatedEvents.push(event.detail.eventId));
    });
    for (const key of ["Enter", "Space"]) {
      await page.keyboard.press(key);
      await expect(target).toHaveClass(/is-selected/);
    }
    if (id === one.loop.id) {
      await expect(field("Loop iterations")).toHaveText("1/3");
      await expect(page.getByRole("button", {name: "Open first iteration", exact: true})).toBeVisible();
    } else {
      await expect(field("Source")).toHaveText("loop.q1asm:3");
    }
    await target.locator(hitbox).click({position});
    await expect(target).toHaveClass(/is-selected/);
    expect(await page.evaluate(() => window.activatedEvents)).toEqual([id, id, id]);
  }
});

test("standalone hidden and filtered timeline blocks stay outside keyboard selection", async ({page}) => {
  const {one} = fixtures();
  const {svg, selectLoop} = await open(page, one);
  const [issue, acquire, , wait] = one.first;
  const node = (event) => svg.locator(`[data-event-id="${event.id}"]`);
  await selectLoop();
  await page.getByRole("searchbox", {name: "Filter source or kind"}).fill(`${wait.id} wait`);
  await expect(node(issue)).toBeHidden();
  await expect(node(acquire)).toBeHidden();
  await expect(svg.locator(".loop-bracket")).toHaveCount(2);
  await expect(svg.locator(".loop-bracket-start")).toBeHidden();
  await expect(svg.locator(".loop-bracket-end")).toBeHidden();

  const visited = [];
  for (let step = 0; step < 16; step++) {
    await page.keyboard.press("Tab");
    visited.push(await page.evaluate(() => document.activeElement?.dataset.eventId));
  }
  expect(visited.filter(Boolean)).toContain(wait.id);
  expect(visited.filter(Boolean).every((id) => id === wait.id)).toBe(true);
  await node(wait).locator("rect").click();
  await node(acquire).dispatchEvent("keydown", {key: "Enter"});
  await expect(node(wait)).toHaveClass(/is-selected/);
});
